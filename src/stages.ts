// The stage themes of each game: the robot masters' stages plus the fortress
// stages (Wily, Cossack, Dr. X, Proto Man). The song list can show only these.
// Keyed by sound ID, so renaming a track doesn't change it.
import { trackKey } from './storage';

const STAGES: Record<string, number[]> = {
  mm1: [0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x0b, 0x0c],
  mm2: [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09],
  mm3: [0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x12],
  mm4: [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x15, 0x09, 0x16],
  mm5: [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09],
  mm6: [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x09, 0x0b],
};

const STAGE_KEYS = new Set(Object.entries(STAGES).flatMap(([game, ids]) => ids.map((id) => trackKey(game, id))));

export const isStageTrack = (game: string, id: number) => STAGE_KEYS.has(trackKey(game, id));
